import type { ReportData } from "@/lib/export/aggregate";
import { EXPORT_COLORS as C, MONEY_FORMAT } from "@/lib/export/theme";
import { writeSectionTitle, writeSheetHeader } from "@/lib/export/xlsx/header";
import { SheetWriter, type Column, type Sheet } from "@/lib/export/xlsx/sheet-builder";

const COLUMNS: Column[] = [
  { header: "", width: 26 },
  { header: "", width: 16 },
  { header: "", width: 16 },
  { header: "", width: 16 },
  { header: "", width: 16 },
  { header: "", width: 16 },
];

/** Four headline tiles (label over value), Net highlighted in amber like the report's hero tile. */
function writeTiles(sheet: SheetWriter, row: number, report: ReportData): number {
  const { income, expense, net, count } = report.totals;
  const tiles: [string, number, string, string][] = [
    ["Income", income, C.income, MONEY_FORMAT],
    ["Expenses", expense, C.expense, MONEY_FORMAT],
    ["Net", net, net < 0 ? C.expense : C.income, MONEY_FORMAT],
    ["Transactions", count, C.ink, "0"],
  ];
  tiles.forEach(([label, value, color, format], c) => {
    const hero = label === "Net";
    const edge = { style: hero ? "thick" : "thin", color: { rgb: hero ? C.amber : C.hairline } };
    const side = { style: "thin", color: { rgb: hero ? C.amber : C.hairline } };
    const fill = { fgColor: { rgb: C.panel } };
    sheet.set(row, c, { v: label, t: "s", s: { font: { sz: 9, color: { rgb: C.muted } }, fill, border: { top: edge, left: side, right: side }, alignment: { indent: 1 } } });
    sheet.set(row + 1, c, {
      v: value,
      t: "n",
      z: format,
      s: { font: { sz: hero ? 18 : 15, bold: true, color: { rgb: color } }, fill, numFmt: format, border: { bottom: side, left: side, right: side }, alignment: { horizontal: "left", indent: 1 } },
    });
  });
  sheet.rowHeights[row] = { hpt: 18 };
  sheet.rowHeights[row + 1] = { hpt: 30 };
  return row + 3;
}

export function summarySheet(report: ReportData, generatedOn: string): Sheet {
  const sheet = new SheetWriter(COLUMNS.length);
  let row = writeSheetHeader(sheet, "Summary", report, generatedOn);
  row = writeTiles(sheet, row, report);

  if (report.budgets.length > 0) {
    row = writeSectionTitle(sheet, row, "Budgets");
    row = sheet.table(
      row,
      [{ header: "Budget", width: 26 }, { header: "Limit", width: 16, kind: "money" }, { header: "Spent", width: 16, kind: "money" }, { header: "Left", width: 16, kind: "money" }, { header: "Used", width: 16, kind: "percent" }],
      report.budgets.map((b) => ({
        values: [b.label, b.limit, b.spent, b.limit - b.spent, b.ratio],
        options: { tones: [undefined, undefined, undefined, "net", b.state === "over" ? "expense" : b.state === "warn" ? "accent" : undefined] },
      })),
    ) + 1;
  }

  for (const [title, shares, tone] of [
    ["Spending by category", report.expenseByCategory, "expense"],
    ["Income by category", report.incomeByCategory, "income"],
  ] as const) {
    if (shares.length === 0) continue;
    row = writeSectionTitle(sheet, row, title);
    const total = shares.reduce((s, x) => s + x.amount, 0);
    row = sheet.table(
      row,
      [{ header: "Category", width: 26 }, { header: "Amount", width: 16, kind: "money" }, { header: "Share", width: 16, kind: "percent" }],
      [
        ...shares.map((s) => ({ values: [s.category, s.amount, s.share], options: { tone } })),
        { values: ["Total", total, 1], options: { total: true, tone } },
      ],
    ) + 1;
  }

  row = writeSectionTitle(sheet, row, "Wallets");
  row = sheet.table(
    row,
    [
      { header: "Wallet", width: 26 },
      { header: "Income", width: 16, kind: "money" },
      { header: "Expenses", width: 16, kind: "money" },
      { header: "Transfers in", width: 16, kind: "money" },
      { header: "Transfers out", width: 16, kind: "money" },
      { header: "Net change", width: 16, kind: "money" },
    ],
    report.wallets.map((w) => ({
      values: [w.name, w.income, w.expense, w.transfersIn, w.transfersOut, w.net],
      options: { tones: [undefined, "income", "expense", undefined, undefined, "net"] },
    })),
  ) + 1;

  sheet.line(
    row,
    "Generated by Expense Tracker from figures you entered. Not a bank statement or an official financial record.",
    { font: { sz: 8, italic: true, color: { rgb: C.muted } }, alignment: { wrapText: true, vertical: "top" } },
    28,
  );
  return sheet.finish(COLUMNS);
}
