import { PRINT } from "@/lib/export/theme";
import { displayHost, escapeHtml } from "@/lib/report/format";

// The app's mark (Lucide "hand-coins") in amber on a dark tile: inline SVG so
// the print never waits on an image request.
const LOGO_SVG = `
<svg viewBox="0 0 32 32" aria-hidden="true">
  <rect width="32" height="32" rx="7" fill="#27272a" />
  <g transform="translate(4 4)" fill="none" stroke="${PRINT.amber}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">
    <path d="M11 15h2a2 2 0 1 0 0-4h-3c-.6 0-1.1.2-1.4.6L3 17" />
    <path d="m7 21 1.6-1.4c.3-.4.8-.6 1.4-.6h4c1.1 0 2.1-.4 2.8-1.2l4.6-4.4a2 2 0 0 0-2.75-2.91l-4.2 3.9" />
    <path d="m2 16 6 6" />
    <circle cx="16" cy="9" r="2.9" />
    <circle cx="6" cy="5" r="3" />
  </g>
</svg>`;

/** Dark header band with the brand, the title, and the "Personal copy" mark, then the amber stripe. */
export function renderHeader(appName: string, title: string, subtitle: string): string {
  return `
<header>
  <div class="band">
    <div class="band-top">
      <div class="brand">${LOGO_SVG}<span>${escapeHtml(appName)}</span></div>
      <span class="chip">Personal copy</span>
    </div>
    <h1 class="doc-title">${escapeHtml(title)}</h1>
    <p class="doc-subtitle">${escapeHtml(subtitle)}</p>
  </div>
  <div class="stripe"></div>
</header>`;
}

/** Repeats at the foot of every printed page. */
export function renderRunningFooter(appName: string, appUrl: string): string {
  return `
<footer class="running-footer">
  <span><strong>${escapeHtml(appName)}</strong>${escapeHtml(displayHost(appUrl))}</span>
  <span>Personal record, not a bank statement</span>
</footer>`;
}

/**
 * Wording must stay consistent with the Terms ("not an official financial
 * statement") and the Privacy Policy's export section (src/app/(legal)/…).
 */
export function renderDisclaimer(appName: string, generatedOn: string): string {
  return `
<p class="disclaimer">
  Generated by ${escapeHtml(appName)} on ${escapeHtml(generatedOn)} from figures you entered.
  It is for your personal reference only. It is <strong>not</strong> a bank statement or an
  official financial record, and isn't issued or certified by any bank or authority.
</p>`;
}
